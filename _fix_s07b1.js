const fs = require("fs");
const P = "projects/打戏/00-spec/shots.json";
const spec = JSON.parse(fs.readFileSync(P, "utf8"));

const s = spec.shots.find((x) => x.id === "S07");

/**
 * S07_b1 修两件事：
 *   ① 构图失控：要求"撞击特写"却画成全身双人镜
 *      → 不再用"画面里只有…"的否定句（模型不敏感），改用"这一块占满整个画面"的占比句
 *   ② 接触点穿模：脚与腰的边界糊在一起
 *      → 按规则 6，改画"脚刚压进去的那一瞬"，并明确"脚背与腰腹之间有一道细缝、能看到衣服被压下去但还没贴死"
 */
s.beats[0].frame_prompt = `<Picture 1> 锁定立柱与供桌的相对位置；<Picture 2> 锁定女主的长相、体型与服装；<Picture 3> 锁定男主的长相、体型与服装。 人物是纤细清瘦的自然体型：肩窄、四肢细、胸腹平坦不显轮廓、手臂没有任何隆起的分块肌肉，宽松衣物自然垂坠且没有被肌肉撑起。 皮肤一律哑光、不反光，肤色偏灰偏冷，不出油光、镜面高光与汗水。 地面是夯实的干黄土、铺着散落的干稻草，**干燥、哑光、粗糙，没有任何反光、亮斑或水渍**；地面整片在阴影里。 唯一光源是屋顶破洞漏下的冷青白月光，**只斜照人物上半身与后墙，不落到地面**。 实拍质感、电影感。 竖幅。

【构图——这是本帧最重要的一条，必须照做】
**这是一张极限特写。画面被两条腿和一段腰腹完全占满，没有任何空间留给别的东西。**
- **苏晚踢出的那条腿（从膝盖到脚背）横贯画面**，占画面宽度的一大半，是画面里最长、最显眼的一条线。
- **陆沉的腰腹与一侧髋部填满画面右侧剩下的部分。**
- **画面里能看到的东西只有这四样：她的小腿、她的脚背与黑布武术鞋、他的腰腹、他的T恤。**
- **画面上方边缘切在她的膝盖稍上一点，也切在他的胸口下方——两个人的头和肩都不在画面里。**
- **背景只露出一小条暗色土墙与几根垂下的干草，全部在虚焦里。**

【这一瞬是什么时刻】**不是已经顶实的那一瞬，是脚背刚刚压上他腰腹、布料刚刚被压下去、还没有贴死的那一瞬。**
- **他的T恤在这一小块被压出一个凹面，布料向四周绷紧、起放射状的斜褶。**
- **脚背与腰腹之间留着一道极细的亮缝**——能看出布料被压下去了、但还没完全贴死。**这道缝必须能看见。**
- **脚背绷直、鞋面被拉紧、脚踝的骨点顶起。**

【苏晚的姿势——她的腿不是从一条直立的身体上长出来的】
- **能看到她的支撑腿膝盖在画面左上角、弯得很深、小腿几乎竖直**，说明**她的身体压得很低，整个人是蹲着发的力**。
- **她踢出的腿从髋部完全展开、膝盖绷直、整条腿像一条绷紧的直线。**
- **因为发力太满，她的髋部向前顶出去、超过支撑脚的位置**——腿的根部比她支撑的膝盖更靠近画面右侧。

【陆沉的反应】
- **他的腰腹被这一下顶得向内折**，**髋向画面右侧偏出去**。
- **画面右下角能看见他的一只手臂被甩开、手腕松垂**，手指失力张开。
- **他的T恤下摆被气浪整片掀起、飘向画面右上方。**

【环境反馈】**接触点周围一圈细碎的干草屑与浮尘正向外炸开**，颗粒在月光边缘可见。

【材质】布料是哑光棉与亚麻的质感，**没有任何油光或镜面高光**。皮肤哑光、偏灰偏冷。

【硬约束】画面里不能出现文字、水印或分屏。不要画全身、不要画两个人的脸、不要画双人全景、不要画标准的武术架势、不要挺胸直背、不要双脚全掌平稳着地。Negative: full body shot, two full figures, faces in frame, wide shot, both heads visible, textbook martial arts stance, upright chest, symmetrical stable stance, foot merging into body, limb overlapping, 畸形脚、脚与身体融合、多余肢体、`;

// H3 里的 0.0–1.0s 段同步
s.h3.integrated_multimodal_description = s.h3.integrated_multimodal_description.replace(
  /\[0\.0–1\.0s\] 极近撞击特写：[^\n]*/,
  `[0.0–1.0s] **极限特写，画面被腿与腰腹完全占满**：她踢出的腿（膝到脚背）横贯画面占一大半，他的腰腹与髋填满画面右侧；上方切在她膝上、切在他胸口下方，**两个人的头和肩都不在画面里**。**这一瞬是脚背刚压上、布料刚被压下去、还没贴死的那一瞬**——T恤压出凹面、四周起放射斜褶，**脚背与腰腹之间留着一道能看见的细缝**，避免穿模。脚背绷直鞋面拉紧。**她的支撑腿膝盖在画面左上角弯得很深、小腿几乎竖直，说明她整个人蹲得很低在发力**；踢出的腿从髋展开膝盖绷直成一条直线；**髋部前顶、超过支撑脚位置**。他被顶得腰腹内折、髋向右侧偏出；画面右下角见他一臂甩开手腕松垂手指失张；T恤下摆被气浪掀向画面右上方。接触点周围干草屑与浮尘向外炸开。`
);

