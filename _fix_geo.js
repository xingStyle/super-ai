const fs = require("fs");
const P = "projects/打戏/00-spec/shots.json";
const spec = JSON.parse(fs.readFileSync(P, "utf8"));

/**
 * 把「反标准架势」的几何描述补进 S07_b1 和 S04_b1 ——
 * 这两帧的发力方姿势仍可能被画成直立。
 */

// S07_b1：撞击特写，她的姿势要几何化
{
  const s = spec.shots.find((x) => x.id === "S07");
  const b = s.beats[0];
  b.frame_prompt = b.frame_prompt.replace(
    "【发力方的力学——不能是站着踢】苏晚的支撑腿**膝盖微屈、脚掌整个踩实地面、脚趾抓地**；踢出的腿**从髋部完全展开、伸直**；因为把力量全送了出去，她的**髋部向前顶出、肩线向后倒压**作为配重（这就是为什么真实的侧踢上身会后仰而不是笔直站着）。",
    `【发力方的力学——不能是站着踢，必须画成这个样子】
- **她的支撑腿膝盖弯到小腿几乎竖直、臀部坐低，身体高度只剩站立时的一半**；**支撑脚脚掌整个踩实干土、脚趾抓地，鞋底边缘压得陷进土里一点。**
- **她整个上身向后仰、向后压，肩线明显落在支撑脚的后方**——从侧面看，**她的身体与踢出的腿构成一个"反写的 V"，支撑脚是那个 V 的底端尖**。
- **踢出的腿从髋部完全展开、膝盖绷直、脚背绷紧脚趾前指**，整条腿像一条直线。
- **她的髋部向前顶出、越过支撑脚的正上方**——这是把力量全部送出去的样子，物理上不可能直立。
- **双臂张开在两侧、一臂向后甩出一臂收在胸前**作为配重。`
  );
  s.h3.integrated_multimodal_description = s.h3.integrated_multimodal_description.replace(
    /\[0\.0–1\.0s\] 极近撞击特写：[^\n]*/,
    `[0.0–1.0s] 极近撞击特写：只装下苏晚的小腿脚背与陆沉的腰腹，**不出现任何脸**。脚背顶进上腹，腰腹内凹、衣料起放射褶、双臂被甩开。**苏晚的支撑腿膝盖弯到小腿几乎竖直、臀部坐低，身体高度只剩站立时一半**，支撑脚脚掌踩实脚趾抓地；**她整个上身向后仰、肩线落在支撑脚后方，身体与踢出的腿构成"反写的 V"**；踢出的腿从髋展开膝盖绷直脚背绷紧；**髋部前顶越过支撑脚正上方**；双臂张开一臂后甩配重。`
  );
}

// S04_b1：低扫前的压低，也要几何化
{
  const s = spec.shots.find((x) => x.id === "S04");
  const b = s.beats[0];
  b.frame_prompt = b.frame_prompt.replace(
    "**她整个人先沉下去**：**支撑腿（右腿）深屈、膝盖超过脚尖、臀部向下坐**，重心**完全压到右腿**；**左腿向侧前方拖出去、膝盖微弯、脚尖点地**，准备扫。",
    `**她整个人先沉下去，必须画成这个样子：**
- **支撑腿（右腿）深屈、膝盖明显超过脚尖、臀部向下坐到很低**，**她的身体高度只有站立时的三分之二**；**右脚脚掌整个踩实、脚趾抓地。**
- **左腿向侧前方拖出去、膝盖弯着、脚尖点地**，**左脚脚跟完全离地**。
- **从侧面看，她的髋部很低、膝盖朝前顶出、上身向前压下去**——整个人是一个**压紧的、前倾的三角形**，不是一个直立的桩。`
  );
  s.h3.integrated_multimodal_description = s.h3.integrated_multimodal_description.replace(
    /- \[0\.0–0\.8s\] 她侧后方单人镜：[^\n]*/,
    `- [0.0–0.8s] 她侧后方单人镜：**只有苏晚**。支撑腿深屈、膝盖明显超过脚尖、臀部坐到很低（身体高度只剩站立时三分之二）、右脚脚掌踩实脚趾抓地；左腿侧前拖出膝盖弯着、左脚跟完全离地；**从侧面看髋部很低、膝盖朝前顶、上身向前压，整个人是压紧的前倾三角形，不是直立的桩**；上身向支撑腿一侧倾斜配重；双臂自然张开护着；头低着盯画外地面。`
  );
}

fs.writeFileSync(P, JSON.stringify(spec, null, 2), "utf8");
console.log("已把几何化姿态补进 S07_b1 与 S04_b1");
