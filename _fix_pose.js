// 反武术架势的负面词（每条打戏提示词都必须带）
const ANTI_POSE = `不要画标准的武术架势、不要扎马步、不要挺胸直背、不要双脚全掌平稳着地、不要对称稳定的站姿、不要运动员的教科书动作、不要站着出腿、不要躯干垂直。Negative: textbook martial arts stance, horse stance, upright chest, straight vertical torso, both feet planted flat, symmetrical stable stance, standing kick, posing, action figure pose,`;

function addAntiPose(s) {
  if (!s.h3) return;
  const t = s.h3.integrated_multimodal_description;
  if (ANTI_POSE.split("。")[0].slice(0, 10) && t.includes("不要画标准的武术架势")) return;
  s.h3.integrated_multimodal_description = t.replace(
    /负面约束（必须避免）：/,
    `负面约束（必须避免）：${ANTI_POSE}`
  );
}

