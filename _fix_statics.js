const fs = require("fs");
const P = "projects/打戏/00-spec/shots.json";
const spec = JSON.parse(fs.readFileSync(P, "utf8"));

/**
 * 按规则 4.8.3：静态帧画不出来的动作（让开、来不及、跟上来、挡在门口）
 * 在单帧里必然被画成"站着"。处理方式：
 *   A. 直接删掉这一帧（由前后帧承载）
 *   B. 改成局部特写（只拍正在形变的那个部位）
 *   C. 给一个"标准架势无法满足"的不对称几何
 */

// ───── S02：删掉 b3「他侧身让开」─────
// 理由："让开后的位置"和"本来就站在这儿"长得一样。而 b4 已经写了
// "他已经落在她推空的方向之外"，信息不丢失。3 秒 3 帧，节奏更紧。
{
  const s = spec.shots.find((x) => x.id === "S02");
  s.beats = s.beats.filter((b) => b.name !== "单人：他侧身让开");
  // 重排时间：0 / 0.7 / 1.6
  s.beats[0].t = 0;   // 蓄势
  s.beats[1].t = 0.7; // 掌推出
  s.beats[2].t = 1.6; // 她失重
  s.title = "她先出手，一掌推空";
  s.intent = "她主动推，他侧身让开，她推空前倾。三个帧：她蓄势、掌推空（特写）、她失控前跌（他在错开的位置）。";
  s.camera_note = "b1 她的单人、b2 掌的局部特写、b3 双人但两人都在动。";
  s.timing.basis = "0s 她蓄势 → 0.7s 掌推出（推空）→ 1.6s 她失控前跌，共 3 秒。删去「他让开」独占的中间帧：那个动作在单帧里与「站着」无法区分，信息由 b3 承载。";
  s.h3.integrated_multimodal_description = s.h3.integrated_multimodal_description.replace(
    /- \[1\.6–2\.3s\][^\n]*\n/,
    ""
  ).replace(
    /\[2\.3–3\.0s\]/,
    "[1.6–3.0s]"
  ).replace(
    /\*\*镜头分段（前三个都是单人镜，只有最后一个同框；不许全程双人全景）\*\*/,
    "**镜头分段（两个单人/局部 + 一个双人；不许全程双人全景，也不许有任何一帧是「一个人站着」）**"
  );
  console.log("S02 → 3 帧");
}

