// 重建 Picture 声明（帧数变了）
function rebuildHead(s) {
  const refUse = s.picture_use || [];
  const beatStart = refUse.length + 1;
  const parts = [];
  refUse.forEach((u, i) => parts.push(`\u003cPicture ${i + 1}\u003e 只用于${u}，不要照搬它的构图`));
  (s.beats || []).forEach((b, i) =>
    parts.push(
      `\u003cPicture ${beatStart + i}\u003e 对应第 ${(Number(b.t) || 0).toFixed(1)} 秒「${b.name}」这一帧，只用于锁定该帧的姿态与取景，不要照搬它的构图`
    )
  );
  const h3 = s.h3.integrated_multimodal_description;
  const firstBlank = h3.indexOf("\n\n");
  s.h3.integrated_multimodal_description =
    parts.join("；") + "。" + (firstBlank >= 0 ? h3.slice(firstBlank) : "\n\n" + h3);
}
for (const s of spec.shots) if (s.beats && s.beats.length && s.h3) rebuildHead(s);

// image_prompt 用首帧
for (const s of spec.shots) {
  if (!s.beats || !s.beats.length) continue;
  s.image_prompt = s.beats[0].frame_prompt.replace(/\n\n【硬约束】[\s\S]*$/, "").trim();
}

