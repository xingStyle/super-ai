  s.title = "他反击：撞门框、蹬框、肘撞到她肩上";
  s.intent = "他用门框借力，把身体当锤子送出去。三个帧：撞框压紧、脚蹬框（特写）、肘撞中肩（特写）。";
  s.camera_note = "b1 单人全身、b2 脚部特写、b3 接触点特写。没有「等反应」的静止帧。";
